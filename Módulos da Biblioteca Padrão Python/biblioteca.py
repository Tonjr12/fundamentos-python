# Usando o módulo 'math' para funções matemáticas
import math
raiz = math.sqrt(25)
print(f"A raiz quadrada de 25 é: {raiz}")

# Usando o módulo 'random' para gerar números aleatórios
import random
numeros_aleatorios = random.randint(0, 100)
print(f"Um número aleatório entre 1 e 100: {numeros_aleatorios}")

